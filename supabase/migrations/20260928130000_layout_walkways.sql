--
-- ## 왜
--
-- W40 운영 초안에서 CNC-613(M3-C2 열 한가운데)이 B6 MAIN SUB6 로 추천됐다. 추천의 "이웃"이 사방 거리였기
-- 때문에, 613 과 **등이 맞닿은** 옆 열(631–639)의 B6 블록을 이웃으로 보고 라인 중간에 끼워 넣은 것이다.
-- 현장의 작업 단위는 거리가 아니라 **동선**이다: 빨간 선을 사이에 두고 마주본 두 열이 한 작업자의 동선이고,
-- 동선은 가로 통로에서 끊긴다(1공장 48개). 추천은 이 단위로 모델·공정을 묶어야 한다(한 동선 = 한 공정 최우선,
-- 둘이면 좌우 한쪽 열씩 → 위·아래 끝 블록, 중간 끼워넣기 금지).
--
-- ## 무엇을
--
-- machine_layout_positions 에 두 열을 더한다.
--   walkway       '<동>-<동선 순번>-<U|D>' — U/D 는 가로 통로 위/아래. 같은 동·같은 U/D 에서 순번 ±1 이 옆 동선.
--   walkway_side  'L' | 'R' — 동선의 왼쪽/오른쪽 열. 같은 (walkway, side) 가 한 열이다.
-- 둘 다 NULL 허용: 동선을 아직 모르는 도면(2공장 등)은 NULL 이고, 추천은 예전 거리 방식으로 동작한다.
--
-- 값은 원본 Excel 의 빨간 테두리에서 scripts/extract-layout-walkways.py 로 뽑았다
-- (Setting CNC.xlsx sha256 c219463c5f6190b5e46e9999ad97546ff37f3c29306746f264a00e8346eb0277). 셀 주소(cell)까지 대조해, 도면 좌표를 넣은 20260925120000 과 같은 셀인지
