-- Codex 감사 #6 마무리: 구 close_shift_upsert(v1) 제거.
--
-- ⚠ **이 마이그레이션은 v2 를 쓰는 코드가 프로덕션에 배포된 뒤에만 적용한다.**
--   먼저 적용하면 v1 을 호출하는 현재 배포본의 교대 마감이 전부 실패한다.
--
-- ══ 왜 두 단계로 나눴나 ══════════════════════════════════════════════════
--
-- v2 는 인자가 셋 늘었다(p_window_start, p_window_end, p_expected_digest).
-- CLAUDE.md 의 규약대로 `create or replace` 는 인자 목록이 다르면 덮어쓰지 않고
-- **오버로드**를 만들므로, v1 을 같은 이름으로 교체할 수 없었다. 그렇다고 같은
-- 마이그레이션에서 v1 을 DROP 하면 마이그레이션과 코드 배포 사이에 어느 순서로도
-- 피할 수 없는 "함수 없음" 창이 생긴다(PostgREST 스키마 캐시 리로드 지연까지 겹친다).
--
--   마이그레이션 먼저 -> 옛 코드가 v1 호출 -> 함수 없음 -> 500
--   코드 먼저        -> 새 코드가 v2 호출 -> 함수 없음 -> 500
--
-- 그래서 새 이름(v2)으로 만들고 v1 을 남겼다. 그 결과 순서가 자유로워진다:
--
--   ① 20260729160000 적용 (v2 추가, v1 유지)  -> 옛 코드는 v1 을 계속 쓴다. 무해.
--   ② 코드 배포                                -> 새 코드가 v2 를 쓴다.
--   ③ 이 마이그레이션                          -> 아무도 안 쓰는 v1 을 지운다.
--
-- 어느 시점에도 호출되는 함수가 없는 구간이 생기지 않는다.
--
-- ══ 적용 전 확인 ═════════════════════════════════════════════════════════
--
-- 1. 프로덕션 배포가 READY 이고, 그 배포가 v2 를 호출하는 커밋인지.
-- 2. 저장소에 `close_shift_upsert` 를 부르는 코드가 없는지
--    (`grep -rn "close_shift_upsert'" src/` — v2 만 나와야 한다).
-- 3. 최근 로그에 close-shift 500 이 없는지.

drop function if exists public.close_shift_upsert(
  uuid, date, text, integer, integer, integer, integer, numeric, numeric, integer, integer
);
